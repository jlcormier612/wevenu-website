#!/usr/bin/env node
/**
 * Build-time WebP variants for large curated marketing photography.
 * Originals under public/ are never modified.
 *
 * Skips upscaling. Writes:
 *   public/marketing/derived/*.webp
 *   public/marketing/derived/manifest.json
 *   lib/marketing/static-photo-assets.generated.ts
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const marketingRoot = path.resolve(__dirname, "..");
const publicRoot = path.join(marketingRoot, "public");
const outDir = path.join(publicRoot, "marketing", "derived");
const generatedTs = path.join(
  marketingRoot,
  "lib/marketing/static-photo-assets.generated.ts",
);

const WIDTHS = [640, 960, 1280, 1920];
/** High-quality WebP; fall back to original in UI if inspection rejects. */
const WEBP_QUALITY = 82;

/** Large photography / editorial — not UI screenshots. */
const SOURCES = [
  { id: "hero-hospitality-airy", src: "marketing/hero-hospitality-airy.png" },
  { id: "journey-first-hello", src: "marketing/journey-first-hello.png" },
  { id: "journey-collaboration", src: "marketing/journey-collaboration.png" },
  { id: "journey-final-cheers", src: "marketing/journey-final-cheers.png" },
  { id: "venue-your-way-editorial", src: "marketing/venue-your-way-editorial.jpg" },
  { id: "operations-venue-ready", src: "marketing/operations-venue-ready.png" },
  { id: "getting-started-editorial", src: "marketing/getting-started-editorial.png" },
  { id: "getting-started-hero", src: "marketing/getting-started/getting-started-hero.jpg" },
  { id: "ecosystem-venue", src: "marketing/ecosystem-venue.png" },
  { id: "ecosystem-client", src: "marketing/ecosystem-client.png" },
  { id: "ecosystem-vendor", src: "marketing/ecosystem-vendor.png" },
  { id: "our-first-friends-editorial", src: "marketing/our-first-friends-editorial.png" },
  { id: "tour-grounds", src: "marketing/tour-grounds.jpg" },
  { id: "our-story-behind-the-scenes", src: "marketing/our-story-behind-the-scenes.jpg" },
  {
    id: "walkthrough-personal-conversation",
    src: "marketing/walkthrough-personal-conversation.jpg",
  },
  {
    id: "features-journey-primary",
    src: "marketing/features-spotlights/spotlight-journey-consultation.jpg",
  },
  {
    id: "features-hero-golden-hour",
    src: "marketing/features-hero-golden-hour-garden.jpg",
  },
];

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function generateOne(entry) {
  const inputPath = path.join(publicRoot, entry.src);
  await fs.access(inputPath);
  const meta = await sharp(inputPath).metadata();
  const variants = {};
  for (const w of WIDTHS) {
    if (meta.width && w > meta.width * 1.02) continue;
    const outName = `${entry.id}-${w}.webp`;
    const outPath = path.join(outDir, outName);
    await sharp(inputPath)
      .resize({ width: w, withoutEnlargement: true, fit: "inside" })
      .webp({ quality: WEBP_QUALITY, effort: 4 })
      .toFile(outPath);
    const st = await fs.stat(outPath);
    variants[String(w)] = {
      path: `/marketing/derived/${outName}`,
      bytes: st.size,
    };
  }
  if (Object.keys(variants).length === 0) {
    throw new Error(`No variants produced for ${entry.id} (source ${meta.width}px)`);
  }
  return {
    id: entry.id,
    source: `/${entry.src}`,
    width: meta.width ?? 0,
    height: meta.height ?? 0,
    variants,
  };
}

function writeGeneratedTs(images) {
  const ids = Object.keys(images);
  const lines = [];
  lines.push("/** AUTO-GENERATED by scripts/pregenerate-static-images.mjs — do not edit. */");
  lines.push("");
  lines.push(
    `export type StaticPhotoId =\n  ${ids.map((id) => `| "${id}"`).join("\n  ")};`,
  );
  lines.push("");
  lines.push("export type StaticPhotoAsset = {");
  lines.push("  id: StaticPhotoId;");
  lines.push("  source: string;");
  lines.push("  width: number;");
  lines.push("  height: number;");
  lines.push("  variants: Record<string, string>;");
  lines.push("};");
  lines.push("");
  lines.push(
    "export const STATIC_PHOTO_ASSETS: Record<StaticPhotoId, StaticPhotoAsset> = {",
  );
  for (const id of ids) {
    const img = images[id];
    const variantEntries = Object.entries(img.variants)
      .map(([w, v]) => `      "${w}": "${v.path}"`)
      .join(",\n");
    lines.push(`  "${id}": {`);
    lines.push(`    id: "${id}",`);
    lines.push(`    source: "${img.source}",`);
    lines.push(`    width: ${img.width},`);
    lines.push(`    height: ${img.height},`);
    lines.push(`    variants: {`);
    lines.push(variantEntries);
    lines.push(`    },`);
    lines.push(`  },`);
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

async function main() {
  await ensureDir(outDir);
  // Remove prior derived webps so stale IDs cannot linger
  for (const name of await fs.readdir(outDir)) {
    if (name.endsWith(".webp") || name === "manifest.json") {
      await fs.unlink(path.join(outDir, name));
    }
  }

  const manifest = {
    generatedAt: new Date().toISOString(),
    webpQuality: WEBP_QUALITY,
    widths: WIDTHS,
    images: {},
  };

  for (const entry of SOURCES) {
    const result = await generateOne(entry);
    manifest.images[entry.id] = result;
    const sizes = Object.entries(result.variants)
      .map(([w, v]) => `${w}:${Math.round(v.bytes / 1024)}KB`)
      .join(" ");
    console.log(`OK ${entry.id} (${result.width}x${result.height}) ${sizes}`);
  }

  await fs.writeFile(
    path.join(outDir, "manifest.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );
  await fs.writeFile(generatedTs, writeGeneratedTs(manifest.images));
  console.log(`Wrote manifest + ${generatedTs}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
